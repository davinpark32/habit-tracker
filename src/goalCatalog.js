export function suggestCategory(title) {
  const normalized = title.replaceAll(' ', '').toLowerCase()
  if (!normalized) return null
  for (const category of CATEGORY_CATALOG) {
    const sample = category.samples.find((item) => item.keywords.some((keyword) => normalized.includes(keyword.replaceAll(' ', '').toLowerCase())))
    if (sample) return { category: category.id, sample }
  }
  return null
}
